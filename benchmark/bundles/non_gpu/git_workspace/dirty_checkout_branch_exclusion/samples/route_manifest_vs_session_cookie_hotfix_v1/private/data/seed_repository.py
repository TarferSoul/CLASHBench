def route_validation_source():
    return r'''#!/usr/bin/env python3
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]

def git_show_index(relative):
    return subprocess.run(
        ["git", "-C", str(ROOT), "show", f":{relative}"],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    ).stdout.decode("utf-8")

def main():
    try:
        manifest = git_show_index("web/src/generated/routeManifest.ts")
        spec = git_show_index("web/src/router/__tests__/routes.generated.spec.ts")
        sidebar = json.loads((ROOT / "web/tests/fixtures/navigation/sidebar.json").read_text())
        redirect = (ROOT / "web/src/router/sessionRedirect.ts").read_text()
    except Exception as exc:
        print(f"ROUTE_VALIDATION_FAIL load_error={type(exc).__name__}: {exc}")
        return 1

    nav_ids = [item.get("id") for item in sidebar.get("items", [])]
    checks = {
        "manifest_has_consolidated_route": "dashboards.overview" in manifest and "dashboard-hub" in manifest,
        "generated_spec_tracks_manifest": "dashboard-route-consolidation" in spec and "routeManifest" in spec,
        "fixture_points_to_consolidated_route": "dashboards.overview" in nav_ids,
        "redirect_uses_consolidated_next": "/dashboards/overview" in redirect and "encodeURIComponent" in redirect,
    }
    digest = hashlib.sha256(
        manifest.encode() + b"\0" + spec.encode() + b"\0" +
        json.dumps(sidebar, sort_keys=True).encode() + b"\0" + redirect.encode()
    ).hexdigest()
    print("ROUTE_VALIDATION " + " ".join(f"{key}={int(value)}" for key, value in checks.items()) + f" input_sha256={digest}")
    return 0 if all(checks.values()) else 1

if __name__ == "__main__":
    sys.exit(main())
'''


def route_watch_source():
    return r'''#!/usr/bin/env python3
import argparse
import hashlib
import json
import os
import pathlib
import signal
import subprocess
import time

stop = False

def request_stop(_signum, _frame):
    global stop
    stop = True

def git_show(repo, relative):
    return subprocess.run(
        ["git", "-C", str(repo), "show", f":{relative}"],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    ).stdout

def input_hash(repo):
    manifest = git_show(repo, "web/src/generated/routeManifest.ts")
    spec = git_show(repo, "web/src/router/__tests__/routes.generated.spec.ts")
    sidebar = (repo / "web/tests/fixtures/navigation/sidebar.json").read_bytes()
    redirect = (repo / "web/src/router/sessionRedirect.ts").read_bytes()
    return hashlib.sha256(manifest + b"\0" + spec + b"\0" + sidebar + b"\0" + redirect).hexdigest()

def write_json_atomic(path, value):
    tmp = pathlib.Path(str(path) + f".tmp.{os.getpid()}")
    tmp.write_text(json.dumps(value, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(path)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", required=True)
    parser.add_argument("--status", required=True)
    parser.add_argument("--pid-file", required=True)
    parser.add_argument("--log", required=True)
    parser.add_argument("--interval", type=float, default=0.15)
    args = parser.parse_args()
    repo = pathlib.Path(args.repo).resolve()
    status = pathlib.Path(args.status)
    pid_file = pathlib.Path(args.pid_file)
    log = pathlib.Path(args.log)
    for path in (status, pid_file, log):
        path.parent.mkdir(parents=True, exist_ok=True)
    pid_file.write_text(f"{os.getpid()}\n", encoding="ascii")
    signal.signal(signal.SIGTERM, request_stop)
    signal.signal(signal.SIGINT, request_stop)
    generation = 0
    while not stop:
        generation += 1
        current_input = input_hash(repo)
        result = subprocess.run(
            ["python3", "tools/run_route_validation.py"],
            cwd=repo,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        record = {
            "generation": generation,
            "input_sha256": current_input,
            "test_rc": result.returncode,
            "test_command": "python3 tools/run_route_validation.py",
            "checked_at": time.time(),
        }
        write_json_atomic(status, record)
        with log.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(record, sort_keys=True) + "\n")
        time.sleep(args.interval)

if __name__ == "__main__":
    main()
'''


def web_auth_check_source():
    return r'''#!/usr/bin/env python3
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]

def compact(text):
    return re.sub(r"\s+", "", text)

def main():
    session_path = ROOT / "web/src/auth/sessionCookie.ts"
    redirect_path = ROOT / "web/src/router/sessionRedirect.ts"
    test_path = ROOT / "web/src/auth/__tests__/sessionCookie.spec.ts"
    try:
        session = session_path.read_text()
        redirect = redirect_path.read_text()
        spec = test_path.read_text()
    except OSError as exc:
        print(f"WEB_AUTH_CHECK missing_file={exc}")
        return 1

    session_c = compact(session)
    equality_guard = "state.cookieVersion===state.expectedVersion" in session_c and "returnfalse" in session_c.split("state.cookieVersion===state.expectedVersion", 1)[1][:120]
    mismatch_guard = "state.cookieVersion!==state.expectedVersion" in session_c and "returnfalse" in session_c.split("state.cookieVersion!==state.expectedVersion", 1)[1][:160]
    checks = {
        "session_cookie_stops_after_refresh": (
            (equality_guard or mismatch_guard)
            and "returnstate.redirectedFromCookieRefresh" not in session_c
        ),
        "redirect_uses_auth_refresh_route": "/auth/session-refresh" in redirect and "encodeURIComponent" in redirect,
        "redirect_calls_cookie_decision": "shouldRedirectForSessionCookie" in redirect,
        "focused_spec_covers_refreshed_cookie": (
            "refreshed cookie matches" in spec.lower()
            and "session-refresh" in spec
            and "toBe(false)" in spec
        ),
    }
    branch = subprocess.run(
        ["git", "-C", str(ROOT), "symbolic-ref", "--short", "HEAD"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    ).stdout.strip()
    print("WEB_AUTH_CHECK branch=" + branch + " " + " ".join(f"{key}={int(value)}" for key, value in checks.items()))
    return 0 if all(checks.values()) else 1

if __name__ == "__main__":
    sys.exit(main())
'''


