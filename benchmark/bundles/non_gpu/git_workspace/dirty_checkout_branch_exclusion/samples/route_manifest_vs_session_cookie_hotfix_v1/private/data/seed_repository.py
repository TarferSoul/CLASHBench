#!/usr/bin/env python3
"""Create the deterministic React-style repository for this sample."""

import argparse
import json
import os
import pathlib
import shutil
import subprocess


BASE_ENV = {
    "GIT_AUTHOR_NAME": "Web Platform",
    "GIT_AUTHOR_EMAIL": "web-platform@example.test",
    "GIT_COMMITTER_NAME": "Web Platform",
    "GIT_COMMITTER_EMAIL": "web-platform@example.test",
}


def run(repo, *args, env=None):
    merged = os.environ.copy()
    merged.update(BASE_ENV)
    if env:
        merged.update(env)
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=merged,
    ).stdout.strip()


def write(repo, relative, text):
    path = repo / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_json(repo, relative, value):
    write(repo, relative, json.dumps(value, indent=2, sort_keys=True) + "\n")


def commit(repo, message, timestamp):
    env = {
        "GIT_AUTHOR_DATE": timestamp,
        "GIT_COMMITTER_DATE": timestamp,
    }
    run(repo, "add", "-A")
    run(repo, "commit", "-m", message, env=env)


