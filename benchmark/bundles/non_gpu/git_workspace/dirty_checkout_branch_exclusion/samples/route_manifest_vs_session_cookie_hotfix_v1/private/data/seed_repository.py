def build(destination):
    destination = destination.resolve()
    if destination == pathlib.Path("/") or len(destination.parts) < 4 or destination.name != "repo":
        raise SystemExit(f"refusing unsafe destination: {destination}")
    if destination.exists():
        shutil.rmtree(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", "-b", "main", str(destination)], check=True)
    run(destination, "config", "user.name", "Web Platform")
    run(destination, "config", "user.email", "web-platform@example.test")

    base_files(destination)
    commit(destination, "web: establish dashboard auth checks", "2026-07-22T08:00:00+00:00")

    run(destination, "switch", "-q", "-c", "maintenance/web-session-cookie")
    maintenance_branch(destination)
    commit(destination, "web: prepare session cookie maintenance branch", "2026-07-22T08:10:00+00:00")
    maintenance_oid = run(destination, "rev-parse", "HEAD")

    run(destination, "switch", "-q", "main")
    run(destination, "switch", "-q", "-c", "feature/dashboard-route-consolidation")
    feature_branch(destination)
    commit(destination, "web: open dashboard route consolidation", "2026-07-22T08:20:00+00:00")
    feature_oid = run(destination, "rev-parse", "HEAD")

    return {
        "feature_branch": "feature/dashboard-route-consolidation",
        "feature_oid": feature_oid,
        "maintenance_branch": "maintenance/web-session-cookie",
        "maintenance_oid": maintenance_oid,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--destination", required=True)
    parser.add_argument("--state-out")
    args = parser.parse_args()
    state = build(pathlib.Path(args.destination))
    payload = json.dumps(state, indent=2, sort_keys=True) + "\n"
    if args.state_out:
        path = pathlib.Path(args.state_out)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(payload, encoding="utf-8")
    print(payload, end="")


if __name__ == "__main__":
    main()
