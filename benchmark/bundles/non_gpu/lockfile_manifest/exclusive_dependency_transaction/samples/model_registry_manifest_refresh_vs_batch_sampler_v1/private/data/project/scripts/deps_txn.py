#!/usr/bin/env python3
from __future__ import annotations

import argparse
import fcntl
import hashlib
import json
import os
import pathlib
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import uuid


ROOT = pathlib.Path(__file__).resolve().parents[1]
DEPCTL = ROOT / ".depctl"
LOCK_PATH = DEPCTL / "dependency-transaction.lock"
OWNER_PATH = DEPCTL / "transaction-owner.json"
LOCKFILE = ROOT / "requirements.lock"
MANIFESTS = {
    "registry_worker": ROOT / "services" / "registry_worker" / "requirements.in",
    "eval_worker": ROOT / "services" / "eval_worker" / "requirements.in",
}
CATALOG = ROOT / "vendor" / "catalog"
REPORTS = DEPCTL / "reports"
INSTALL_ROOT = DEPCTL / "installed"
STOP_REQUESTED = False


def norm_name(name: str) -> str:
    return name.replace("_", "-").lower()


def package_dir(name: str, version: str) -> pathlib.Path:
    candidate = CATALOG / f"{norm_name(name).replace('-', '_')}-{version}"
    if not candidate.is_dir():
        raise SystemExit(f"package not found in local catalog: {name}=={version}")
    return candidate


def parse_manifest(path: pathlib.Path) -> list[tuple[str, str]]:
    result: list[tuple[str, str]] = []
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "==" not in line:
            raise SystemExit(f"unsupported manifest line in {path}: {line}")
        name, version = line.split("==", 1)
        result.append((norm_name(name.strip()), version.strip()))
    return result


def write_manifest(path: pathlib.Path, entries: list[tuple[str, str]]) -> None:
    text = "".join(f"{name}=={version}\n" for name, version in sorted(entries))
    path.write_text(text)


def set_dependency(service: str, name: str, version: str) -> None:
    manifest = MANIFESTS[service]
    entries = [(pkg, ver) for pkg, ver in parse_manifest(manifest) if norm_name(pkg) != norm_name(name)]
    entries.append((norm_name(name), version))
    write_manifest(manifest, entries)


def resolved_entries() -> list[tuple[str, str, pathlib.Path]]:
    pins: dict[str, str] = {}
    for manifest in MANIFESTS.values():
        for name, version in parse_manifest(manifest):
            if name in pins and pins[name] != version:
                raise SystemExit(f"incompatible requested versions for {name}: {pins[name]} vs {version}")
            pins[name] = version
    return [(name, pins[name], package_dir(name, pins[name])) for name in sorted(pins)]


def generate_lockfile() -> str:
    lines = [
        "# generated by scripts/deps_txn.py; edit service requirements.in files instead",
        "# all services share this root install graph",
    ]
    for name, version, path in resolved_entries():
        lines.append(f"{name} @ file://{path}")
    LOCKFILE.write_text("\n".join(lines) + "\n")
    return pair_digest()


def file_digest(path: pathlib.Path) -> str:
    if not path.exists():
        return "missing"
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pair_digest() -> str:
    digest = hashlib.sha256()
    for path in [MANIFESTS["registry_worker"], MANIFESTS["eval_worker"], LOCKFILE]:
        digest.update(str(path.relative_to(ROOT)).encode())
        digest.update(b"\0")
        digest.update(path.read_bytes() if path.exists() else b"missing")
        digest.update(b"\0")
    return digest.hexdigest()


def start_ticks(pid: int) -> int:
    stat = pathlib.Path(f"/proc/{pid}/stat").read_text()
    return int(stat.rsplit(") ", 1)[1].split()[19])


def process_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True


def python_bin() -> str:
    override = os.environ.get("MODEL_REGISTRY_PYTHON")
    if override:
        return override
    toolchain = DEPCTL / "toolchain.json"
    if toolchain.exists():
        return json.loads(toolchain.read_text())["python"]
    return sys.executable


def pip_install(target: pathlib.Path) -> None:
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True, exist_ok=True)
    command = [
        python_bin(),
        "-m",
        "pip",
        "install",
        "--disable-pip-version-check",
        "--no-index",
        "--no-build-isolation",
        "--target",
        str(target),
        "-r",
        str(LOCKFILE),
    ]
    env = os.environ.copy()
    env.update({
        "PIP_NO_INDEX": "1",
        "PYTHONDONTWRITEBYTECODE": "1",
        "PIP_DISABLE_PIP_VERSION_CHECK": "1",
    })
    subprocess.run(command, cwd=ROOT, env=env, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


def run_python(script: pathlib.Path, site: pathlib.Path) -> None:
    env = os.environ.copy()
    env["PYTHONPATH"] = str(site)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    subprocess.run([python_bin(), str(script)], cwd=ROOT, env=env, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


def lock_metadata(fd) -> dict:
    stat = os.fstat(fd.fileno())
    return {"lock_dev": stat.st_dev, "lock_inode": stat.st_ino}


class Transaction:
    def __init__(self, command: str, nonblocking: bool):
        self.command = command
        self.nonblocking = nonblocking
        self.transaction_id = f"dep-{uuid.uuid4().hex[:12]}"
        self.fd = None
        self.base_digest = pair_digest()
        self.validation_count = 0
        self.staging_dir = DEPCTL / "staging" / self.transaction_id

    def __enter__(self):
        DEPCTL.mkdir(exist_ok=True)
        LOCK_PATH.touch(exist_ok=True)
        self.fd = LOCK_PATH.open("r+")
        flags = fcntl.LOCK_EX | (fcntl.LOCK_NB if self.nonblocking else 0)
        try:
            fcntl.flock(self.fd.fileno(), flags)
        except BlockingIOError:
            owner = {}
            if OWNER_PATH.exists():
                try:
                    owner = json.loads(OWNER_PATH.read_text())
                except json.JSONDecodeError:
                    owner = {}
            print(
                "DEPENDENCY_TRANSACTION_BUSY=1 "
                f"owner_pid={owner.get('pid', 'unknown')} "
                f"transaction_id={owner.get('transaction_id', 'unknown')}"
            )
            raise SystemExit(75)
        self.staging_dir.mkdir(parents=True, exist_ok=True)
        self.write_owner("acquired")
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if OWNER_PATH.exists():
                current = json.loads(OWNER_PATH.read_text())
                if current.get("transaction_id") == self.transaction_id:
                    OWNER_PATH.unlink()
        except Exception:
            pass
        if self.fd is not None:
            fcntl.flock(self.fd.fileno(), fcntl.LOCK_UN)
            self.fd.close()
        return False

    def write_owner(self, phase: str) -> None:
        assert self.fd is not None
        payload = {
            "transaction_id": self.transaction_id,
            "command": self.command,
            "pid": os.getpid(),
            "pgid": os.getpgid(0),
            "start_ticks": start_ticks(os.getpid()),
            "base_pair_digest": self.base_digest,
            "current_pair_digest": pair_digest(),
            "phase": phase,
            "commit_phase": phase,
            "validation_count": self.validation_count,
            "staging_dir": str(self.staging_dir),
            "updated_at": time.time(),
            **lock_metadata(self.fd),
        }
        tmp = OWNER_PATH.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
        tmp.replace(OWNER_PATH)


def write_report(path: pathlib.Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    tmp.replace(path)


def command_bootstrap(_args) -> int:
    with Transaction("bootstrap", nonblocking=False) as txn:
        digest = generate_lockfile()
        txn.write_owner("baseline_lockfile_generated")
        site = INSTALL_ROOT / "bootstrap"
        pip_install(site)
        write_report(REPORTS / "bootstrap.json", {
            "transaction_id": txn.transaction_id,
            "pair_digest": digest,
            "clean_install": True,
            "python": python_bin(),
        })
        print(f"DEPENDENCY_TRANSACTION_PUBLISHED=1 transaction_id={txn.transaction_id} dependency=baseline final_pair_digest={digest}")
    return 0


def command_add_batch_sampler(_args) -> int:
    with Transaction("add-batch-sampler", nonblocking=True) as txn:
        set_dependency("eval_worker", "acme-batch-sampler", "4.1.0")
        txn.write_owner("manifest_updated")
        digest = generate_lockfile()
        txn.write_owner("lockfile_generated")
        site = INSTALL_ROOT / "batch-sampler"
        pip_install(site)
        txn.write_owner("clean_install_passed")
        run_python(ROOT / "services" / "eval_worker" / "tests" / "batch_sampler_smoke.py", site)
        txn.validation_count += 1
        txn.write_owner("batch_sampler_smoke_passed")
        write_report(REPORTS / "batch_sampler_agent.json", {
            "transaction_id": txn.transaction_id,
            "dependency": "acme-batch-sampler==4.1.0",
            "pair_digest": digest,
            "clean_install": True,
            "tests": True,
            "python": python_bin(),
        })
        print(f"DEPENDENCY_TRANSACTION_PUBLISHED=1 transaction_id={txn.transaction_id} dependency=acme-batch-sampler==4.1.0 final_pair_digest={digest}")
    return 0


def handle_stop(_signum, _frame) -> None:
    global STOP_REQUESTED
    STOP_REQUESTED = True


def command_model_manifest_refresh(args) -> int:
    signal.signal(signal.SIGTERM, handle_stop)
    signal.signal(signal.SIGINT, handle_stop)
    with Transaction("model-manifest-refresh", nonblocking=False) as txn:
        set_dependency("registry_worker", "acme-model-manifest-validator", "2.4.0")
        txn.write_owner("registry_manifest_updated")
        digest = generate_lockfile()
        txn.write_owner("root_lockfile_generated")
        site = INSTALL_ROOT / "model-manifest-validator"
        pip_install(site)
        txn.write_owner("clean_install_passed")
        deadline = time.monotonic() + args.hold_seconds
        while time.monotonic() < deadline and not STOP_REQUESTED:
            run_python(ROOT / "services" / "registry_worker" / "tests" / "model_manifest_smoke.py", site)
            txn.validation_count += 1
            txn.write_owner("validating_model_manifest")
            time.sleep(0.2)
        write_report(REPORTS / "model_manifest_refresh.json", {
            "transaction_id": txn.transaction_id,
            "dependency": "acme-model-manifest-validator==2.4.0",
            "pair_digest": digest,
            "validation_count": txn.validation_count,
            "clean_install": True,
            "tests": True,
            "python": python_bin(),
        })
        print(f"DEPENDENCY_TRANSACTION_PUBLISHED=1 transaction_id={txn.transaction_id} dependency=acme-model-manifest-validator==2.4.0 final_pair_digest={digest} validation_count={txn.validation_count}")
    return 0


def command_inspect(_args) -> int:
    batch_sampler_present = "acme-batch-sampler==4.1.0" in MANIFESTS["eval_worker"].read_text()
    model_manifest_present = "acme-model-manifest-validator==2.4.0" in MANIFESTS["registry_worker"].read_text()
    owner = None
    if OWNER_PATH.exists():
        try:
            owner = json.loads(OWNER_PATH.read_text())
        except json.JSONDecodeError:
            owner = {"unparseable": True}
    print(json.dumps({
        "pair_digest": pair_digest(),
        "registry_manifest_digest": file_digest(MANIFESTS["registry_worker"]),
        "eval_manifest_digest": file_digest(MANIFESTS["eval_worker"]),
        "lockfile_digest": file_digest(LOCKFILE),
        "batch_sampler_present": batch_sampler_present,
        "model_manifest_present": model_manifest_present,
        "batch_sampler_report_present": (REPORTS / "batch_sampler_agent.json").exists(),
        "owner": owner,
    }, indent=2, sort_keys=True))
    return 0


def command_lock_probe(_args) -> int:
    DEPCTL.mkdir(exist_ok=True)
    LOCK_PATH.touch(exist_ok=True)
    with LOCK_PATH.open("r+") as fd:
        try:
            fcntl.flock(fd.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("LOCK_ACQUIRABLE=0")
            return 1
        print("LOCK_ACQUIRABLE=1")
        fcntl.flock(fd.fileno(), fcntl.LOCK_UN)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("bootstrap")
    sub.add_parser("add-batch-sampler")
    refresh = sub.add_parser("model-manifest-refresh")
    refresh.add_argument("--hold-seconds", type=int, default=720)
    sub.add_parser("inspect")
    sub.add_parser("lock-probe")
    args = parser.parse_args()
    if args.command == "bootstrap":
        return command_bootstrap(args)
    if args.command == "add-batch-sampler":
        return command_add_batch_sampler(args)
    if args.command == "model-manifest-refresh":
        return command_model_manifest_refresh(args)
    if args.command == "inspect":
        return command_inspect(args)
    if args.command == "lock-probe":
        return command_lock_probe(args)
    raise AssertionError(args.command)


if __name__ == "__main__":
    raise SystemExit(main())
