CREATE TABLE feature_partitions (
    partition_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id text NOT NULL,
    partition_key text NOT NULL UNIQUE,
    object_uri text NOT NULL,
    row_count integer NOT NULL CHECK (row_count > 0),
    content_digest text NOT NULL,
    validation_status text NOT NULL DEFAULT 'pending',
    row_version integer NOT NULL DEFAULT 1,
    registered_by text NOT NULL DEFAULT current_user,
    registered_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE feature_partition_audit (
    audit_id text PRIMARY KEY,
    partition_key text NOT NULL,
    operation text NOT NULL,
    committed_row_version integer NOT NULL,
    recorded_by text NOT NULL DEFAULT current_user,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE closeout_controls (
    event_id text PRIMARY KEY,
    closeout_id text NOT NULL,
    detail text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

